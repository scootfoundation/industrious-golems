package com.scottcaldwell.industriousgolems.behavior;

import com.scottcaldwell.industriousgolems.IndustriousGolems;

import java.util.ArrayList;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;

/**
 * Explicit state machines. A {@link Graph} is declared once per machine: its states (an enum), what each means, where it
 * starts and every transition that is allowed, with the condition that triggers it. A {@link Run} is one running copy; it
 * can only move along declared edges, so a transition nobody described cannot happen quietly. The graphs are also the source
 * of the state-machine diagrams (see {@code docs/state-machines.html}, regenerated by {@code tools/update-state-docs.ps1}).
 */
public final class Machine {
    private Machine() { }

    /** When set (by the game tests), an undeclared transition throws instead of being logged. */
    public static volatile boolean strict;

    /** One declared transition. */
    public record Edge(String from, String to, String when) { }

    /** The static description of a machine. */
    public static final class Graph<S extends Enum<S>> {
        public final String id;
        public final String title;
        public final String summary;
        private final Class<S> type;
        private S start;
        private final Map<S, String> notes;
        private final List<Edge> edges = new ArrayList<>();
        private final Map<S, List<S>> next;

        public Graph(String id, String title, String summary, Class<S> type) {
            this.id = id;
            this.title = title;
            this.summary = summary;
            this.type = type;
            this.notes = new EnumMap<>(type);
            this.next = new EnumMap<>(type);
        }

        /** Describes a state. */
        public Graph<S> state(S state, String note) {
            notes.put(state, note);
            return this;
        }

        /** The state a fresh run begins in. */
        public Graph<S> start(S state) {
            start = state;
            return this;
        }

        /** Declares a transition and what causes it. */
        public Graph<S> edge(S from, S to, String when) {
            edges.add(new Edge(from.name(), to.name(), when));
            next.computeIfAbsent(from, k -> new ArrayList<>()).add(to);
            return this;
        }

        boolean allows(S from, S to) {
            List<S> list = next.get(from);
            return list != null && list.contains(to);
        }

        public Run<S> run() {
            if (start == null) throw new IllegalStateException(id + " has no start state");
            return new Run<>(this);
        }

        /** The graph as JSON, for the diagram page. */
        public String json() {
            StringBuilder b = new StringBuilder();
            b.append("{\"id\":").append(q(id)).append(",\"title\":").append(q(title)).append(",\"summary\":").append(q(summary))
                    .append(",\"start\":").append(q(start.name())).append(",\"states\":[");
            boolean first = true;
            for (S s : type.getEnumConstants()) {
                if (!first) b.append(',');
                first = false;
                b.append("{\"name\":").append(q(s.name())).append(",\"note\":").append(q(notes.getOrDefault(s, ""))).append('}');
            }
            b.append("],\"edges\":[");
            first = true;
            for (Edge e : edges) {
                if (!first) b.append(',');
                first = false;
                b.append("{\"from\":").append(q(e.from())).append(",\"to\":").append(q(e.to())).append(",\"when\":").append(q(e.when())).append('}');
            }
            return b.append("]}").toString();
        }

        /** States nobody ever enters or leaves are almost certainly a mistake in the declaration. */
        public List<String> problems() {
            List<String> out = new ArrayList<>();
            for (S s : type.getEnumConstants()) {
                boolean in = s == start, outgoing = false;
                for (Edge e : edges) {
                    if (e.to().equals(s.name())) in = true;
                    if (e.from().equals(s.name())) outgoing = true;
                }
                if (!in) out.add(id + ": " + s + " is never entered");
                if (!outgoing && !notes.getOrDefault(s, "").startsWith("(end)")) out.add(id + ": " + s + " has no way out and is not marked (end)");
                if (!notes.containsKey(s)) out.add(id + ": " + s + " has no description");
            }
            return out;
        }

        private static String q(String s) {
            return '"' + s.replace("\\", "\\\\").replace("\"", "\\\"") + '"';
        }
    }

    /** One running copy of a machine. */
    public static final class Run<S extends Enum<S>> {
        private final Graph<S> graph;
        private S state;

        private Run(Graph<S> graph) {
            this.graph = graph;
            this.state = graph.start;
        }

        public S state() {
            return state;
        }

        public boolean is(S s) {
            return state == s;
        }

        /** Moves along a declared edge. Staying where it is is always fine. */
        public void to(S next) {
            if (next == state) return;
            if (!graph.allows(state, next)) {
                String message = graph.id + ": undeclared transition " + state + " -> " + next;
                if (strict) throw new IllegalStateException(message);
                IndustriousGolems.LOGGER.warn(message);
            }
            state = next;
        }

        /** Back to the start state, for the next time the task runs. */
        public void reset() {
            state = graph.start;
        }
    }
}
